# Regenerates audio-map.js from the shared Google Drive folder of MP3 files.
#   pwsh        scripts/build-audio-map.ps1      (PowerShell 7, also used by GitHub Actions)
#   powershell -ExecutionPolicy Bypass -File scripts/build-audio-map.ps1   (Windows PowerShell)
# The web app plays the MP3s directly from Drive (nothing is downloaded). The folder must be shared as
# "Anyone with the link - Viewer". The workflow .github/workflows/update-audio-map.yml runs this on a schedule,
# so MP3s newly added to the Drive folder are picked up automatically.
# An MP3 is matched to a song by the number at the start of its file name, e.g. "117 My Song.mp3" -> "117 My Song"
# (a letter suffix such as "002a" is kept, so "002a ...mp3" matches "002a ..." and not "002").

param(
  [string]$FolderId = "1myQ0gmbUFMBWpe-uLwJ_bESwX2jlYcQn"
)

$ErrorActionPreference = "Stop"
$out = Join-Path (Split-Path $PSScriptRoot -Parent) "audio-map.js"

# Reads one Drive folder (and its sub-folders, up to 3 levels deep) and returns its audio files.
function Get-Folder([string]$folderId, [int]$depth) {
  $url = "https://drive.google.com/embeddedfolderview?id=$([uri]::EscapeDataString($folderId))"
  $html = (Invoke-WebRequest -UseBasicParsing -Uri $url -TimeoutSec 60).Content
  $chunks = $html -split 'class="flip-entry" id="entry-' | Select-Object -Skip 1
  foreach ($c in $chunks) {
    $id = ($c -split '"', 2)[0]
    if ($id -notmatch '^[A-Za-z0-9_-]+$') { continue }
    if ($c -match '/drive/folders/') {
      if ($depth -lt 3) { Get-Folder $id ($depth + 1) }
      continue
    }
    if ($c -notmatch '/file/d/' -or $c -notmatch 'type/audio') { continue }   # audio files only
    $name = [System.Net.WebUtility]::HtmlDecode(([regex]::Match($c, 'flip-entry-title">([^<]*)<')).Groups[1].Value)
    $m = [regex]::Match($name, '^\s*(\d{1,3})([A-Za-z]?)(?![0-9A-Za-z])')
    $num = if ($m.Success) { $m.Groups[1].Value.PadLeft(3, "0") + $m.Groups[2].Value.ToLower() } else { "" }
    [pscustomobject]@{ n = $num; name = $name; id = $id }
  }
}

$items = @(Get-Folder $FolderId 0 | Group-Object id | ForEach-Object { $_.Group[0] })
if (-not $items.Count) { throw "No audio files found - refusing to overwrite audio-map.js" }

$json = "[" + (($items | ForEach-Object { $_ | ConvertTo-Json -Compress }) -join ",") + "]"
Set-Content -Path $out -Value "// Generated by scripts/build-audio-map.ps1 - do not edit by hand.`nwindow.AUDIO_MAP = $json;" -Encoding UTF8
"Wrote $(@($items).Count) audio entries to $out"
